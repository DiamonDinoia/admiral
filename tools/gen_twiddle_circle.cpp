// Prints include/admiral/detail/twiddle_circle.hpp. The values are the run-time fold's own
// sincos_small_eval<long double> plus sincos_octant_mix, cast to double once, on the full
// unit circle of den 65536: entry i holds sin and cos of i / 65536 turns. A power-of-two
// den d reads the same circle at stride 65536 / d: power-of-two scaling is exact, so the
// residual angle and the fold land on the same bits the fold computes for d. The plan
// build then pays one load a twiddle and no run-time long double math.
#include <admiral/detail/ct_math.hpp>

#include <cfloat>
#include <cstdio>

// The committed bits are the 64-bit-mantissa long double fold rounded once to double.
// A host with a different long double format folds different bits; fail loud there.
static_assert(LDBL_MANT_DIG == 64 && LDBL_MAX_EXP > 1024,
              "the circle generator needs the x86 64-bit-mantissa long double format");

int main() {
    using namespace admiral::detail;
    std::printf("#pragma once\n\n");
    std::printf("// Generated by tools/gen_twiddle_circle.cpp. Do not edit.\n");
    std::printf("// Full unit circle at den 65536, fold bits rounded once to double: entry i holds\n");
    std::printf("// sin and cos of i / 65536 turns. A power-of-two den d reads entry num * (65536/d).\n\n");
    std::printf("#include <array>\n\n");
    std::printf("#include \"ct_math.hpp\"\n\n");
    std::printf("namespace admiral {\nnamespace detail {\nnamespace portable_trig {\n\n");
    std::printf("inline constexpr std::size_t kPow2CircleDen = 65536;\n\n");
    std::printf("inline constexpr std::array<ct_sincos_v<double>, kPow2CircleDen> pow2_circle{{\n");
    for (std::size_t i = 0; i < 65536; ++i) {
        const std::size_t oct = (8 * i) / 65536;
        const std::size_t rem = 8 * i - oct * 65536;
        const long double res =
            static_cast<long double>(rem) *
            (ct_pi<long double> / (static_cast<long double>(4) * static_cast<long double>(65536)));
        const ct_sincos_v<long double> w =
            sincos_octant_mix<long double>(oct, sincos_small_eval<long double>(res));
        std::printf("{%a, %a},\n", static_cast<double>(w.s), static_cast<double>(w.c));
    }
    std::printf("}};\n\n}\n}\n}\n");
    return 0;
}
